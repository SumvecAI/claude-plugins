def _missing_deps_message() -> str:
    return (
        "[generate_pdf] weasyprint / markdown not installed — skipping PDF generation.\n"
        "[generate_pdf] To enable PDF output: pip install weasyprint markdown\n"
        "[generate_pdf] The Markdown audit report has still been written; you can\n"
        "[generate_pdf] re-run this script after installing the dependencies."
    )


def _sanitize_host(host: str) -> str:
    return re.sub(r"[^a-z0-9-]", "-", host.lower()).strip("-")


def _derive_host_from_filename(md_path: Path) -> str:
    # Existing filename pattern: aiso-audit-<host>-<YYYY-MM-DD>.md
    name = md_path.stem  # strips .md
    m = re.match(r"aiso-audit-(.+)-(\d{4}-\d{2}-\d{2})$", name)
    if m:
        return m.group(1)
    return _sanitize_host(name)


def _host_from_url(url: str) -> str:
    parsed = urlparse(url if "://" in url else f"https://{url}")
    return _sanitize_host(parsed.netloc or url)


def _resolve_logo_path(script_path: Path, override: str | None) -> Path | None:
    if override:
        p = Path(override).expanduser().resolve()
        return p if p.exists() else None
    default = script_path.parent.parent / "assets" / "sumvec-logo.svg"
    return default if default.exists() else None


