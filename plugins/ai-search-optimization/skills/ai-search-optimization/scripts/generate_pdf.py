def _extract_title(md_text: str) -> str:
    for line in md_text.splitlines():
        s = line.strip()
        if s.startswith("# "):
            return s[2:].strip()
    return "AI Search Optimization Audit"


def _html_escape(s: str) -> str:
    return (
        s.replace("&", "&amp;")
        .replace("<", "&lt;")
        .replace(">", "&gt;")
        .replace('"', "&quot;")
    )


def _logo_as_data_uri(logo_path: Path | None) -> str | None:
    if not logo_path:
        return None
    try:
        svg = logo_path.read_text(encoding="utf-8")
    except OSError:
        return None
    import base64

    b64 = base64.b64encode(svg.encode("utf-8")).decode("ascii")
    return f"data:image/svg+xml;base64,{b64}"


def _default_output_path(md_path: Path, host: str, generated_at: dt.datetime) -> Path:
    stamp = generated_at.strftime("%Y-%m-%d-%H%M")
    return md_path.parent / f"{host}-{stamp}.pdf"


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Render an AISO audit Markdown report to a Sumvec-branded PDF."
    )
    parser.add_argument("md_path", help="Path to the audit Markdown file.")
    parser.add_argument("--out", help="Output PDF path. Default: <host>-<YYYY-MM-DD>-<HHMM>.pdf next to the input.")
    parser.add_argument("--logo", help="Path to an SVG/PNG logo. Default: bundled assets/sumvec-logo.svg.")
    parser.add_argument(
        "--target-url",
        help="The URL that was audited. Used for the cover and filename. "
        "If omitted, derived from the input filename.",
    )
    args = parser.parse_args()

    md_path = Path(args.md_path).expanduser().resolve()
    if not md_path.exists():
        print(f"[generate_pdf] Input not found: {md_path}", file=sys.stderr)
        return 1

    try:
        import markdown  # noqa: F401
        from weasyprint import HTML  # noqa: F401
    except ImportError:
        print(_missing_deps_message())
        return 0

    md_text = md_path.read_text(encoding="utf-8")
    generated_at = dt.datetime.now()

    if args.target_url:
        host = _host_from_url(args.target_url)
        target_url_display = args.target_url
    else:
        host = _derive_host_from_filename(md_path)
        target_url_display = host.replace("-", ".")

    out_path = (
        Path(args.out).expanduser().resolve()
        if args.out
        else _default_output_path(md_path, host, generated_at)
    )

    script_path = Path(__file__).resolve()
    logo_path = _resolve_logo_path(script_path, args.logo)
    logo_data_uri = _logo_as_data_uri(logo_path)

    html_str = _build_html(md_text, target_url_display, generated_at, logo_data_uri)

    from weasyprint import HTML  # local import — already verified above

    HTML(string=html_str, base_url=str(script_path.parent)).write_pdf(str(out_path))
    print(f"[generate_pdf] PDF written: {out_path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
