#!/usr/bin/env python3
"""
generate_pdf.py — Render an AISO audit Markdown report to a Sumvec-branded PDF.

Usage:
    python generate_pdf.py <path-to-audit.md> [--out <path>] [--logo <path>] [--target-url <url>]

Output:
    By default, writes the PDF next to the input file with the filename pattern
    <host>-<YYYY-MM-DD>-<HHMM>.pdf, where <host> is derived from --target-url if
    provided, or parsed out of the input filename otherwise.

Dependencies:
    weasyprint, markdown
        pip install weasyprint markdown

If weasyprint is missing, the script prints an install instruction and exits 0
so it never blocks the rest of the audit run.

Branding:
    Reads the bundled `assets/sumvec-logo.svg` (sits in the same skill bundle,
    one directory above `scripts/`). Brand palette from BRAND_GUIDE.md:
        Sumvec Blue   #00A5E0
        Sumvec Orange #FF8101
        Dark Navy     #1E2A3A
        Warm Gray     #808080
"""

