import argparse
import datetime as dt
import re
import sys
from pathlib import Path
from urllib.parse import urlparse


SUMVEC_BLUE = "#00A5E0"
SUMVEC_ORANGE = "#FF8101"
DARK_NAVY = "#1E2A3A"
